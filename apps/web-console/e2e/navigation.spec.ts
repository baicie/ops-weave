test('theme preference persists while credentials and asset data clear on reload', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/#/inventory')
  const token = page.getByRole('textbox', { name: '平台开发 Token（仅保存在当前标签页内存）' })
  await token.fill(TOKEN_OK)
  await page.getByRole('button', { name: '切换到深色模式' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(token).toHaveValue('')
  await expect(page.locator('[data-stat="total"]')).toHaveText('—')
  const stored = await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))
  expect(stored).toEqual({ local: { 'opsweave.ui.theme': 'dark', 'opsweave.ui.layout': 'standard' }, session: {} })
  await page.getByRole('button', { name: '切换到浅色模式' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
})

