test('rail hover flyouts stay inside a short viewport and close when resized', async ({ page }) => {
  await page.setViewportSize({ width: 1024, height: 300 })
  await page.goto('/#/inventory')
  await page.getByRole('button', { name: '收起导航', exact: true }).click()
  const nav = page.getByRole('navigation', { name: '产品模块' })
  const integration = nav.getByRole('button', { name: '数据接入', exact: true })
  await integration.hover()
  await expect(nav.getByRole('link', { name: '采集运行记录', exact: true })).toBeVisible()
  const flyout = page.locator('.nav-flyout:visible')
  const bounds = await flyout.boundingBox()
  expect(bounds!.x).toBeGreaterThan(64)
  expect(bounds!.y).toBeGreaterThanOrEqual(8)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(292)
  await nav.getByRole('link', { name: '数据源中心', exact: true }).hover()
  await expect(integration).toHaveAttribute('aria-expanded', 'true')
  const afterHover = await flyout.boundingBox()
  expect(afterHover!.y + afterHover!.height).toBeLessThanOrEqual(292)
  await page.getByRole('heading', { name: '资产', exact: true }).hover()
  await expect(flyout).not.toBeVisible()
  await integration.hover()
  await expect(flyout).toBeVisible()
  await page.setViewportSize({ width: 390, height: 650 })
  await expect(flyout).not.toBeVisible()
  await page.getByRole('button', { name: '切换导航', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '移动端导航' }).getByRole('link', { name: '数据源中心', exact: true })).toBeVisible()
})

test('every product destination can be opened from its rail group without API calls', async ({ page }) => {
  const calls: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) calls.push(request.url()) })
  await page.goto('/#/inventory')
  await page.getByRole('button', { name: '收起导航', exact: true }).click()
  const nav = page.getByRole('navigation', { name: '产品模块' })
  for (const route of ROUTES.filter(item => item.navigation !== false)) {
    const group = nav.locator('[data-nav-group="' + route.group + '"]')
    await group.getByRole('button').click()
    await group.getByRole('link', { name: route.label, exact: true }).click()
    await expect(page).toHaveURL(new RegExp('#' + route.path + '$'))
    await expect(page.getByRole('main').getByRole('heading').first()).toBeVisible()
  }
  expect(calls).toEqual([])
})

